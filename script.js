// DOM Elements
const pages = document.querySelectorAll('.page-section');
const navItems = document.querySelectorAll('.nav-item');
const sideNav = document.getElementById('side-nav');
const navOverlay = document.getElementById('nav-overlay');
const navOpen = document.getElementById('nav-open');
const navClose = document.getElementById('nav-close');

const langToggle = document.getElementById('lang-toggle');
const langText = document.getElementById('lang-text');
const themeToggle = document.getElementById('theme-toggle');

const categoryCards = document.querySelectorAll('.category-card');
const sectionGrid = document.getElementById('section-grid');
const categoryTitleDisplay = document.getElementById('category-title-display');
const backBtn = document.querySelector('.back-btn');

const questionText = document.getElementById('question-text');
const optionsContainer = document.getElementById('options-container');
const questionCountText = document.getElementById('question-count');
const categoryLabel = document.getElementById('category-label');
const currentScoreText = document.getElementById('current-score');
const progressBar = document.getElementById('progress-bar');
const timerText = document.getElementById('timer-text');
const timerPathRemaining = document.getElementById('timer-path-remaining');

const finalScoreText = document.getElementById('final-score');
const totalQuestionsText = document.getElementById('total-questions');
const percentageText = document.getElementById('percentage');
const performanceMsg = document.getElementById('performance-msg');

const restartBtn = document.getElementById('restart-btn');
const shareBtn = document.getElementById('share-btn');
const nextBtn = document.getElementById('next-btn');
const submitEarlyBtn = document.getElementById('submit-early-btn');

const quizSection = document.getElementById('quiz-section');
const pwaToast = document.getElementById('pwa-toast');
const pwaInstallBtn = document.getElementById('pwa-install-btn');

// Quiz State
let currentLanguage = 'en';
let selectedCategory = '';
let selectedSection = 0;
let currentQuestions = [];
let currentQuestionIndex = 0;
let score = 0;
let timer;
let timeLeft = 15;
let deferredPrompt;

// Initialization
function init() {
    // Navigation Logic
    navOpen.addEventListener('click', () => {
        sideNav.classList.add('open');
        navOverlay.classList.add('show');
    });

    [navClose, navOverlay].forEach(el => el.addEventListener('click', () => {
        sideNav.classList.remove('open');
        navOverlay.classList.remove('show');
    }));

    navItems.forEach(item => {
        item.addEventListener('click', () => {
            const pageId = item.getAttribute('data-page');
            showPage(pageId);
            navItems.forEach(i => i.classList.remove('active'));
            item.classList.add('active');
            sideNav.classList.remove('open');
            navOverlay.classList.remove('show');
        });
    });

    // Language Toggle
    langToggle.addEventListener('click', () => {
        currentLanguage = currentLanguage === 'en' ? 'hi' : 'en';
        langText.textContent = currentLanguage === 'en' ? 'HI' : 'EN';
        updateUI();
        if (quizSection.classList.contains('active')) {
            renderQuestion();
        }
    });

    // Theme Toggle
    themeToggle.addEventListener('click', () => {
        const body = document.body;
        const icon = themeToggle.querySelector('i');
        if (body.getAttribute('data-theme') === 'dark') {
            body.removeAttribute('data-theme');
            icon.classList.replace('fa-sun', 'fa-moon');
        } else {
            body.setAttribute('data-theme', 'dark');
            icon.classList.replace('fa-moon', 'fa-sun');
        }
    });

    // Category Selection
    categoryCards.forEach(card => {
        card.addEventListener('click', () => {
            selectedCategory = card.getAttribute('data-category');
            showSectionSelection();
        });
    });

    backBtn.addEventListener('click', () => showPage('home-section'));

    // Quiz Controls
    nextBtn.addEventListener('click', () => {
        currentQuestionIndex++;
        if (currentQuestionIndex < currentQuestions.length) {
            renderQuestion();
        } else {
            showResults();
        }
    });

    submitEarlyBtn.addEventListener('click', () => {
        if (confirm(currentLanguage === 'en' ? "Submit quiz?" : "क्विज़ सबमिट करें?")) {
            showResults();
        }
    });

    restartBtn.addEventListener('click', () => showPage('home-section'));
    shareBtn.addEventListener('click', shareResult);

    // PWA Logic
    window.addEventListener('beforeinstallprompt', (e) => {
        e.preventDefault();
        deferredPrompt = e;
        pwaToast.classList.add('show');
    });

    pwaInstallBtn.addEventListener('click', () => {
        pwaToast.classList.remove('show');
        deferredPrompt.prompt();
    });

    if ('serviceWorker' in navigator) {
        navigator.serviceWorker.register('sw.js');
    }

    updateUI();
}

function showPage(pageId) {
    pages.forEach(page => {
        page.classList.remove('active');
        if (page.id === pageId) page.classList.add('active');
    });
    // Scroll to top
    window.scrollTo(0,0);
}

function updateUI() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerHTML = translations[currentLanguage][key];
    });
}

function showSectionSelection() {
    const data = quizData[selectedCategory];
    categoryTitleDisplay.textContent = currentLanguage === 'en' ? data.title_en : data.title_hi;

    sectionGrid.innerHTML = '';
    for (let i = 1; i <= 6; i++) {
        const card = document.createElement('div');
        card.classList.add('section-card');
        card.innerHTML = `
            <span class="sec-number">${i}</span>
            <p>${translations[currentLanguage].section_label} ${i}</p>
        `;
        card.addEventListener('click', () => startQuiz(i));
        sectionGrid.appendChild(card);
    }

    showPage('section-select-section');
}

function startQuiz(sectionNum) {
    selectedSection = sectionNum;
    currentQuestions = [...quizData[selectedCategory].sections[sectionNum]];

    // Shuffle the 50 questions
    shuffleArray(currentQuestions);

    score = 0;
    currentQuestionIndex = 0;
    currentScoreText.textContent = score;

    showPage('quiz-section');
    renderQuestion();
}

function renderQuestion() {
    const q = currentQuestions[currentQuestionIndex];

    // Set Question and Options based on Language
    questionText.textContent = currentLanguage === 'en' ? q.q_en : q.q_hi;
    const options = currentLanguage === 'en' ? q.options_en : q.options_hi;

    optionsContainer.innerHTML = '';
    options.forEach((opt, index) => {
        const div = document.createElement('div');
        div.classList.add('option');
        div.textContent = opt;
        div.addEventListener('click', () => handleAnswer(index, div));
        optionsContainer.appendChild(div);
    });

    // Update Meta
    categoryLabel.textContent = currentLanguage === 'en' ? quizData[selectedCategory].title_en : quizData[selectedCategory].title_hi;
    questionCountText.textContent = `${currentQuestionIndex + 1}/${currentQuestions.length}`;
    progressBar.style.width = `${((currentQuestionIndex + 1) / currentQuestions.length) * 100}%`;

    nextBtn.disabled = true;
    startTimer();
}

function handleAnswer(index, el) {
    clearInterval(timer);
    const correctIdx = currentQuestions[currentQuestionIndex].answer;
    const options = optionsContainer.querySelectorAll('.option');

    options.forEach(o => o.classList.add('disabled'));

    if (index === correctIdx) {
        if (el) el.classList.add('correct');
        score++;
        currentScoreText.textContent = score;
    } else {
        if (el) el.classList.add('wrong');
        options[correctIdx].classList.add('correct');
    }

    nextBtn.disabled = false;
}

function startTimer() {
    clearInterval(timer);
    timeLeft = 15;
    updateTimerUI();
    const circularTimer = document.querySelector('.circular-timer');
    circularTimer.classList.remove('warning');

    timer = setInterval(() => {
        timeLeft--;
        updateTimerUI();
        if (timeLeft <= 5) circularTimer.classList.add('warning');
        if (timeLeft <= 0) {
            clearInterval(timer);
            handleAnswer(-1, null); // Timeout
        }
    }, 1000);
}

function updateTimerUI() {
    timerText.textContent = timeLeft;
    const dashArray = `${((timeLeft / 15) * 283).toFixed(0)} 283`;
    timerPathRemaining.setAttribute('stroke-dasharray', dashArray);
}

function showResults() {
    showPage('result-section');
    const total = currentQuestions.length;
    const perc = Math.round((score / total) * 100);

    finalScoreText.textContent = score;
    totalQuestionsText.textContent = total;
    percentageText.textContent = `${perc}%`;

    performanceMsg.textContent = perc >= 80 ? "Excellent!" : perc >= 50 ? "Good Job!" : "Keep Practicing!";
}

function shareResult() {
    const text = `I scored ${score}/${currentQuestions.length} on AmitQuizX! Can you beat me? 🏆`;
    const url = window.location.href;
    if (navigator.share) {
        navigator.share({ title: 'AmitQuizX', text, url });
    } else {
        window.open(`https://api.whatsapp.com/send?text=${encodeURIComponent(text + " " + url)}`);
    }
}

function shuffleArray(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
}

document.addEventListener('DOMContentLoaded', init);

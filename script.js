// Initialization
function init() {
    // Navigation Logic
    navOpen.addEventListener('click', () => {
        sideNav.classList.add('open');
        navOverlay.classList.add('show');
    });

    [navClose, navOverlay].forEach(el => el.addEventListener('click', () => {
        sideNav.classList.remove('open');
        navOverlay.classList.remove('show');
    }));

    navItems.forEach(item => {
        item.addEventListener('click', () => {
            const pageId = item.getAttribute('data-page');
            showPage(pageId);
            if (pageId === 'leaderboard-section') loadLeaderboard();
            navItems.forEach(i => i.classList.remove('active'));
            item.classList.add('active');
            sideNav.classList.remove('open');
            navOverlay.classList.remove('show');
        });
    });

    // Language Toggle
    langToggle.addEventListener('click', () => {
        playClick();
        currentLanguage = currentLanguage === 'en' ? 'hi' : 'en';
        langText.textContent = currentLanguage === 'en' ? 'HI' : 'EN';
        updateUI();
        if (quizSection.classList.contains('active')) {
            renderQuestion();
        }
    });

    // Theme Toggle
    themeToggle.addEventListener('click', () => {
        playClick();
        const body = document.body;
        const icon = themeToggle.querySelector('i');
        if (body.getAttribute('data-theme') === 'dark') {
            body.removeAttribute('data-theme');
            icon.classList.replace('fa-sun', 'fa-moon');
        } else {
            body.setAttribute('data-theme', 'dark');
            icon.classList.replace('fa-moon', 'fa-sun');
        }
    });

    // Difficulty Filtering
    diffBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            playClick();
            diffBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            selectedDifficulty = btn.getAttribute('data-difficulty');
            showSectionSelection();
        });
    });

    // Category Selection
    categoryCards.forEach(card => {
        card.addEventListener('click', () => {
            playClick();
            selectedCategory = card.getAttribute('data-category');
            showSectionSelection();
        });
    });

    backBtn.addEventListener('click', () => {
        playClick();
        showPage('home-section');
    });

    // Quiz Controls
    nextBtn.addEventListener('click', () => {
        playClick();
        currentQuestionIndex++;
        if (currentQuestionIndex < currentQuestions.length) {
            renderQuestion();
        } else {
            showResults();
        }
    });

    submitEarlyBtn.addEventListener('click', () => {
        playClick();
        if (confirm(currentLanguage === 'en' ? "Submit quiz?" : "क्विज़ सबमिट करें?")) {
            showResults();
        }
    });

    // Lifelines
    lifeline5050.addEventListener('click', apply5050);
    lifelineSkip.addEventListener('click', applySkip);
    lifelineHint.addEventListener('click', applyHint);

    restartBtn.addEventListener('click', () => {
        playClick();
        showPage('home-section');
    });
    shareBtn.addEventListener('click', shareResult);
    downloadCertBtn.addEventListener('click', generateCertificate);

    // PWA Logic
    window.addEventListener('beforeinstallprompt', (e) => {
        e.preventDefault();
        deferredPrompt = e;
        pwaToast.classList.add('show');
    });

    pwaInstallBtn.addEventListener('click', () => {
        pwaToast.classList.remove('show');
        deferredPrompt.prompt();
    });

    if ('serviceWorker' in navigator) {
        navigator.serviceWorker.register('sw.js');
    }

    updateUI();
}

function showPage(pageId) {
    pages.forEach(page => {
        page.classList.remove('active');
        if (page.id === pageId) page.classList.add('active');
    });
    window.scrollTo(0,0);
}

function updateUI() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.innerHTML = translations[currentLanguage][key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = translations[currentLanguage][key];
    });
}

function showSectionSelection() {
    const data = quizData[selectedCategory];
    categoryTitleDisplay.textContent = currentLanguage === 'en' ? data.title_en : data.title_hi;

    sectionGrid.innerHTML = '';
    for (let i = 1; i <= 6; i++) {
        const card = document.createElement('div');
        card.classList.add('section-card');

        // Count questions matching difficulty in this section
        let qCount = 0;
        if (selectedDifficulty === 'all') {
            qCount = data.sections[i].length;
        } else {
            qCount = data.sections[i].filter(q => q.difficulty === selectedDifficulty).length;
        }

        card.innerHTML = `
            <span class="sec-number">${i}</span>
            <p>${translations[currentLanguage].section_label} ${i}</p>
            <small style="color: var(--text-muted)">${qCount} Questions</small>
        `;

        if (qCount > 0) {
            card.addEventListener('click', () => startQuiz(i));
        } else {
            card.style.opacity = '0.5';
            card.style.cursor = 'not-allowed';
        }
        sectionGrid.appendChild(card);
    }

    showPage('section-select-section');
}

function startQuiz(sectionNum) {
    playClick();
    selectedSection = sectionNum;

    let questions = [...quizData[selectedCategory].sections[sectionNum]];
    if (selectedDifficulty !== 'all') {
        questions = questions.filter(q => q.difficulty === selectedDifficulty);
    }

    currentQuestions = questions;
    shuffleArray(currentQuestions);

    // Reset State
    score = 0;
    currentQuestionIndex = 0;
    used5050 = false;
    usedSkip = false;
    usedHint = false;

    resetLifelineUI();
    currentScoreText.textContent = score;

    showPage('quiz-section');
    renderQuestion();
}

function renderQuestion() {
    const q = currentQuestions[currentQuestionIndex];

    // UI Elements Reset
    hintBox.classList.add('hidden');
    questionImgContainer.classList.add('hidden');

    // Set Content
    questionText.textContent = currentLanguage === 'en' ? q.q_en : q.q_hi;
    difficultyLabel.textContent = q.difficulty.toUpperCase();
    difficultyLabel.className = `difficulty-tag ${q.difficulty}`;

    if (q.img) {
        questionImg.src = q.img;
        questionImgContainer.classList.remove('hidden');
    }

    const options = currentLanguage === 'en' ? q.options_en : q.options_hi;
    optionsContainer.innerHTML = '';
    options.forEach((opt, index) => {
        const div = document.createElement('div');
        div.classList.add('option');
        div.textContent = opt;
        div.setAttribute('data-index', index);
        div.addEventListener('click', () => handleAnswer(index, div));
        optionsContainer.appendChild(div);
    });

    categoryLabel.textContent = currentLanguage === 'en' ? quizData[selectedCategory].title_en : quizData[selectedCategory].title_hi;
    questionCountText.textContent = `${currentQuestionIndex + 1}/${currentQuestions.length}`;
    progressBar.style.width = `${((currentQuestionIndex + 1) / currentQuestions.length) * 100}%`;

    nextBtn.disabled = true;
    startTimer();
}

function handleAnswer(index, el) {
    stopTimerSound();
    clearInterval(timer);
    const correctIdx = currentQuestions[currentQuestionIndex].answer;
    const options = optionsContainer.querySelectorAll('.option');

    options.forEach(o => o.classList.add('disabled'));

    if (index === correctIdx) {
        if (el) el.classList.add('correct');
        score++;
        currentScoreText.textContent = score;
        playCorrect();
        triggerVibration([50]);
    } else {
        if (el) el.classList.add('wrong');
        options[correctIdx].classList.add('correct');
        playWrong();
        triggerVibration([100, 50, 100]);
    }

    nextBtn.disabled = false;
}

// Lifeline Functions
function apply5050() {
    if (used5050) return;
    playClick();
    const correctIdx = currentQuestions[currentQuestionIndex].answer;
    const options = Array.from(optionsContainer.querySelectorAll('.option'));

    let removed = 0;
    while (removed < 2) {
        let rand = Math.floor(Math.random() * 4);
        if (rand !== correctIdx && !options[rand].classList.contains('hidden')) {
            options[rand].style.visibility = 'hidden';
            options[rand].classList.add('disabled');
            removed++;
        }
    }

    used5050 = true;
    lifeline5050.disabled = true;
}

function applySkip() {
    if (usedSkip) return;
    playClick();
    usedSkip = true;
    lifelineSkip.disabled = true;
    clearInterval(timer);
    stopTimerSound();

    currentQuestionIndex++;
    if (currentQuestionIndex < currentQuestions.length) {
        renderQuestion();
    } else {
        showResults();
    }
}

function applyHint() {
    if (usedHint) return;
    playClick();
    const q = currentQuestions[currentQuestionIndex];
    hintText.textContent = currentLanguage === 'en' ? q.hint_en : q.hint_hi;
    hintBox.classList.remove('hidden');

    usedHint = true;
    lifelineHint.disabled = true;
}

function resetLifelineUI() {
    lifeline5050.disabled = false;
    lifelineSkip.disabled = false;
    lifelineHint.disabled = false;
}

// Timer Functions
function startTimer() {
    clearInterval(timer);
    timeLeft = 15;
    updateTimerUI();
    const circularTimer = document.querySelector('.circular-timer');
    circularTimer.classList.remove('warning');
    playTimerSound();

    timer = setInterval(() => {
        timeLeft--;
        updateTimerUI();
        if (timeLeft <= 5) {
            circularTimer.classList.add('warning');
        }
        if (timeLeft <= 0) {
            clearInterval(timer);
            stopTimerSound();
            handleAnswer(-1, null);
        }
    }, 1000);
}

function updateTimerUI() {
    timerText.textContent = timeLeft;
    const dashArray = `${((timeLeft / 15) * 283).toFixed(0)} 283`;
    timerPathRemaining.setAttribute('stroke-dasharray', dashArray);
}

// Results & Leaderboard
function showResults() {
    showPage('result-section');
    const total = currentQuestions.length;
    const perc = Math.round((score / total) * 100);

    finalScoreText.textContent = score;
    totalQuestionsText.textContent = total;
    percentageText.textContent = `${perc}%`;

    performanceMsg.textContent = perc >= 80 ? "Excellent!" : perc >= 50 ? "Good Job!" : "Keep Practicing!";

    saveScore(score, total);
}

function saveScore(s, t) {
    const scores = JSON.parse(localStorage.getItem('amitquizx_scores') || '[]');
    scores.push({
        name: userNameInput.value || 'Anonymous',
        score: s,
        total: t,
        date: new Date().toLocaleDateString()
    });
    scores.sort((a,b) => (b.score/b.total) - (a.score/a.total));
    localStorage.setItem('amitquizx_scores', JSON.stringify(scores.slice(0, 10)));
}

function loadLeaderboard() {
    const scores = JSON.parse(localStorage.getItem('amitquizx_scores') || '[]');
    leaderboardBody.innerHTML = '';
    scores.forEach((s, idx) => {
        const tr = document.createElement('tr');
        tr.innerHTML = `
            <td>#${idx + 1}</td>
            <td>${s.name}</td>
            <td>${s.score}/${s.total}</td>
            <td>${s.date}</td>
        `;
        leaderboardBody.appendChild(tr);
    });
}

function generateCertificate() {
    const name = userNameInput.value || "Participant";
    const cat = quizData[selectedCategory].title_en;
    const scoreText = `Score: ${score}/${currentQuestions.length}`;
    const dateText = `Date: ${new Date().toLocaleDateString()}`;

    // Update hidden template
    document.getElementById('cert-name').textContent = name;
    document.getElementById('cert-category').textContent = `${cat} Quiz`;
    document.getElementById('cert-score-text').textContent = scoreText;
    document.getElementById('cert-date-text').textContent = dateText;

    const certTemplate = document.getElementById('cert-template');
    certTemplate.classList.remove('hidden');

    html2canvas(certTemplate).then(canvas => {
        const link = document.createElement('a');
        link.download = `AmitQuizX_Certificate_${name}.png`;
        link.href = canvas.toDataURL();
        link.click();
        certTemplate.classList.add('hidden');
    });
}

function shareResult() {
    const text = `I scored ${score}/${currentQuestions.length} on AmitQuizX! Can you beat me? 🏆`;
    const url = window.location.href;
    if (navigator.share) {
        navigator.share({ title: 'AmitQuizX', text, url });
    } else {
        window.open(`https://api.whatsapp.com/send?text=${encodeURIComponent(text + " " + url)}`);
    }
}

// Audio Helpers
function playClick() { sndClick.currentTime = 0; sndClick.play().catch(()=>{}); }
function playCorrect() { sndCorrect.currentTime = 0; sndCorrect.play().catch(()=>{}); }
function playWrong() { sndWrong.currentTime = 0; sndWrong.play().catch(()=>{}); }
function playTimerSound() { sndTimer.currentTime = 0; sndTimer.play().catch(()=>{}); }
function stopTimerSound() { sndTimer.pause(); }

// Haptic Feedback
function triggerVibration(pattern) {
    if (navigator.vibrate) {
        navigator.vibrate(pattern);
    }
}

function shuffleArray(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
}

